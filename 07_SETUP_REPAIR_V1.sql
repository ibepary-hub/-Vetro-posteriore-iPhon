begin;

alter table public.beparytech_admin_repairs
  add column if not exists deposit_amount numeric(12,2) not null default 0;

alter table public.beparytech_admin_repairs
  drop constraint if exists beparytech_admin_repairs_deposit_nonnegative;
alter table public.beparytech_admin_repairs
  add constraint beparytech_admin_repairs_deposit_nonnegative check (deposit_amount >= 0);

create table if not exists public.beparytech_repair_history (
  id bigint generated by default as identity primary key,
  workspace_owner_id uuid not null,
  repair_id bigint not null,
  actor_user_id uuid,
  action text not null,
  snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_bt_repair_history_workspace_repair on public.beparytech_repair_history(workspace_owner_id,repair_id,created_at desc);

alter table public.beparytech_repair_history enable row level security;

drop policy if exists bt_repair_history_admin_select on public.beparytech_repair_history;
create policy bt_repair_history_admin_select on public.beparytech_repair_history
for select to authenticated using (
  exists (select 1 from public.beparytech_profiles p where p.user_id=auth.uid() and p.active=true and p.role='admin' and p.workspace_owner_id=beparytech_repair_history.workspace_owner_id)
);

drop policy if exists bt_repair_history_admin_insert on public.beparytech_repair_history;
create policy bt_repair_history_admin_insert on public.beparytech_repair_history
for insert to authenticated with check (
  actor_user_id=auth.uid() and exists (select 1 from public.beparytech_profiles p where p.user_id=auth.uid() and p.active=true and p.role='admin' and p.workspace_owner_id=beparytech_repair_history.workspace_owner_id)
);

revoke all on public.beparytech_repair_history from anon;
grant select,insert on public.beparytech_repair_history to authenticated;
grant usage,select on sequence public.beparytech_repair_history_id_seq to authenticated;

commit;
